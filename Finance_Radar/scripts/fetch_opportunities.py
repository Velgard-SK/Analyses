# ── Helpers ───────────────────────────────────────────────────────────────────
TODAY_ISO = datetime.now(timezone.utc).strftime("%Y-%m-%d")

def days_until(date_str: str) -> int:
    d = datetime.fromisoformat(date_str.replace("Z", "+00:00"))
    return (d.replace(tzinfo=timezone.utc) - datetime.now(timezone.utc)).days

def days_since(date_str: str) -> int:
    """Days elapsed since an ISO date. Returns a large number if unparseable."""
    try:
        d = datetime.fromisoformat(date_str.replace("Z", "+00:00"))
        if d.tzinfo is None:
            d = d.replace(tzinfo=timezone.utc)
        return (datetime.now(timezone.utc) - d).days
    except Exception:
        return 10**6

def is_relevant(text: str) -> bool:
    text_lower = text.lower()
    return any(kw.lower() in text_lower for kw in KEYWORDS)

def load_existing() -> dict:
    if DATA_FILE.exists():
        with open(DATA_FILE, encoding="utf-8") as f:
            return json.load(f)
    return {"last_updated": "", "opportunities": []}

def save_data(data: dict):
    data["last_updated"] = datetime.now(timezone.utc).isoformat()
    with open(DATA_FILE, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    # Also write data.js so index.html works when opened directly (file://)
