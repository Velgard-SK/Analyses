# ── Main ──────────────────────────────────────────────────────────────────────
def main():
    print(f"\n{'─'*50}")
    print(f"Velgard Financing Radar — {datetime.now().strftime('%Y-%m-%d %H:%M UTC')}")
    print(f"{'─'*50}\n")

    existing_data = load_existing()
    existing_opps = existing_data.get("opportunities", [])

    print("Fetching from sources...")
    fresh = []
    fresh += fetch_eu_portal()   # live API
    fresh += EIC_HARDCODED       # curated EIC calls
    fresh += NGI_CALLS           # NGI cascade
    fresh += SLOVAK_CALLS        # Slovak national calls
    fresh += OTHER_CALLS         # Eurostars, EUREKA

    print(f"\nMerging {len(fresh)} fetched with {len(existing_opps)} existing...")
    merged, new_calls, closing = merge_opportunities(existing_opps, fresh)

    print(f"  Total: {len(merged)} | New: {len(new_calls)} | Closing: {len(closing)}")

    save_data({"last_updated": "", "opportunities": merged})
    send_email(new_calls, closing)

    print("\n✓ Done.\n")

if __name__ == "__main__":
    main()
